def get_mode_config(predicted_class: str, source_f0_hz: float | None = None) -> dict:
    preset = PRESETS.get(predicted_class, DEFAULT_PRESET)

    return {
        "mode_name": preset["mode_name"],
        "midi_notes": _midi_notes_for_class(predicted_class, source_f0_hz),
        "train_args": preset["train_args"],
        "render_args": preset["render_args"],
        "postprocess": preset["postprocess"],
        "vocoder_hybrid": preset.get("vocoder_hybrid", False),
    }
