"""
mode_selector.py

Instrument-specific generation settings.

MIDI playable range is NOT hardcoded here. When the caller knows this
specific recording's own detected pitch (source_f0_hz), the range is
centered on THAT -- see _range_start_from_f0 -- so rendered notes stay
close to what was actually learned instead of a class-wide average.
Otherwise it falls back to models/class_ranges.json, generated by
train_classifier.py from each class's own audio (see
estimate_class_pitch_range there; re-run train_classifier.py whenever
data/ changes so that fallback stays current).

Synthesis presets (mode_name/train_args/render_args/postprocess) ARE looked
up by class name below, but any class without an entry -- e.g. a brand new
instrument folder that hasn't been hand-tuned yet -- automatically falls
back to DEFAULT_PRESET instead of raising, so "add a data/ folder, retrain"
is enough to get a working (if not perfectly tuned) result.
"""

import json
import math
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
CLASS_RANGES_PATH = PROJECT_ROOT / "models" / "class_ranges.json"

DEFAULT_START_MIDI = 48  # C3
DEFAULT_RANGE_COUNT = 36  # 3 octaves, C3-B5

# Matches train_classifier.py's own floor (see its PITCH_RANGE_MIN_START_MIDI
# comment) -- below this, real instruments essentially don't go, and DDSP
# resynthesis extrapolation becomes unreliable.
PITCH_RANGE_MIN_START_MIDI = 24  # C1


def _range_start_from_f0(f0_hz: float, count: int = DEFAULT_RANGE_COUNT) -> int | None:
    """
    C-aligned window start for `count` notes centered on f0_hz -- same
    snap-to-C, floor-clamped math as train_classifier.py's
    estimate_class_pitch_range, applied to this one recording's own pitch
    instead of a class-wide median, so the range stays close to what was
    actually learned.
    """
    if f0_hz is None or f0_hz <= 0:
        return None
    median_midi = 69.0 + 12.0 * math.log2(f0_hz / 440.0)
    approx_start = median_midi - count / 2.0
    start = int(round(approx_start / 12.0)) * 12
    return max(start, PITCH_RANGE_MIN_START_MIDI)


def make_range(start_midi: int, count: int = 36) -> list[int]:
    """
    Generate a consecutive MIDI-note range.

    Example:
        make_range(24) -> MIDI 24-59, C1-B3, 36 notes
    """
    return list(range(start_midi, start_midi + count))


def _load_class_ranges() -> dict:
    if not CLASS_RANGES_PATH.exists():
        return {}
    try:
        with open(CLASS_RANGES_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return {}


def _midi_notes_for_class(
    predicted_class: str, source_f0_hz: float | None = None
) -> list[int]:
    # Prefer anchoring to what THIS recording actually sounds like over
    # the class-wide range -- see _range_start_from_f0's docstring.
    if source_f0_hz is not None:
        start = _range_start_from_f0(source_f0_hz, DEFAULT_RANGE_COUNT)
        if start is not None:
            return make_range(start, DEFAULT_RANGE_COUNT)

    ranges = _load_class_ranges()
    entry = ranges.get(predicted_class)

    # A missing entry falls back to the default range below -- a malformed
    # entry (e.g. an interrupted write from a crashed train_classifier.py
    # run) should get the same graceful fallback instead of crashing here.
    if not isinstance(entry, dict) or "start_midi" not in entry or "count" not in entry:
        return make_range(DEFAULT_START_MIDI, DEFAULT_RANGE_COUNT)

    return make_range(entry["start_midi"], entry["count"])


